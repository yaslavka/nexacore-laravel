let locale = 'en';

export function getLocale() {
  return locale;
}

export function t(key) {
  return dict[locale]?.[key] ?? dict.en[key] ?? key;
}

export function parseRoute(pathname) {
  const clean = (pathname || '/').replace(/\/+$/, '') || '/';
  const parts = clean.split('/').filter(Boolean);
  if (parts[0] === 'ru' || parts[0] === 'ky') {
    const rest = '/' + parts.slice(1).join('/');
    return { locale: parts[0], path: rest === '/' ? '/' : rest };
  }
  return { locale: 'en', path: clean };
}

export function localizePath(path, nextLocale = locale) {
  const clean = path.startsWith('/') ? path : `/${path}`;
  if (nextLocale === 'en') return clean === '' ? '/' : clean;
  if (clean === '/') return `/${nextLocale}`;
  return `/${nextLocale}${clean}`;
}

export function href(path) {
  const [pathname, query] = String(path).split('?');
  const localized = localizePath(pathname || '/', locale);
  return query ? `${localized}?${query}` : localized;
}

export function detectLocale(pathname) {
  const parsed = parseRoute(pathname);
  if (parsed.locale !== 'en') return parsed.locale;
  const hasPrefix = /^\/(ru|ky)(\/|$)/.test(pathname || '');
  if (hasPrefix) return parsed.locale;
  try {
    const saved = localStorage.getItem('nexacore-lang');
    if (LOCALES.includes(saved)) return saved;
  } catch { /* ignore */ }
  const nav = String(navigator.language || navigator.userLanguage || '').toLowerCase();
  if (nav.startsWith('ru')) return 'ru';
  if (nav.startsWith('ky') || nav.startsWith('kir')) return 'ky';
  return 'en';
}

export function setLocale(next) {
  if (!LOCALES.includes(next)) return locale;
  locale = next;
  document.documentElement.lang = LOCALE_META[next].html;
  document.documentElement.translate = 'yes';
  try { localStorage.setItem('nexacore-lang', next); } catch { /* ignore */ }
  return locale;
}

export function pluralServices(n) {
  if (locale === 'ru') {
    const n10 = n % 10;
    const n100 = n % 100;
    if (n10 === 1 && n100 !== 11) return t('serviceOne');
    if (n10 >= 2 && n10 <= 4 && (n100 < 12 || n100 > 14)) return t('serviceFew');
    return t('serviceMany');
  }
  if (locale === 'en' && n === 1) return t('serviceOne');
  return t('serviceMany');
}

export function packageLabel(name) {
  if (name === 'Basic' || name === 'Базовый' || name === 'Негизги') return t('pkgBasic');
  if (name === 'Custom' || name === 'Индивидуальный' || name === 'Жеке') return t('pkgCustom');
  return name;
}

export function companyAddress() {
  return COMPANY.address[locale] || COMPANY.address.en;
}
